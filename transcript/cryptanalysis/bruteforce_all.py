def load_or_build_isogeny_graph(theta0, p):
    filename = f"graph_p{p}.pkl"

    if os.path.exists(filename):

        print(f"Loading cached graph from {filename}...")

        with open(filename, "rb") as f:
            V = pickle.load(f)

        return V

    print(f"Building full graph for p = {p}...")

    V, _, _ = BFS(theta0, only_isogs=True)
    print(f"Done! Graph has {len(V)} vertices")
    assert len(V) > 10

    print(f"Saving graph to {filename}...")

    with open(filename, "wb") as f:
        pickle.dump(V, f)

    return V


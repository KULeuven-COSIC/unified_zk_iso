def projective_points(F, g):
    """
    Generate all points of P^(2^g - 1)(F).

    Returns canonical projective representatives as tuples.
    """

    N = 2**g

    P = ProjectiveSpace(F, N - 1)

    for pt in P.rational_points():
        yield tuple(pt)



def BFS(start_theta, only_isogs=False, max_depth=None, V_real = []):
    """
    Traverse the graph generated by radical_step.


    Parameters
    ----------
    start_theta:
        Initial theta point

    only_isogs:
        Build the isogeny graph

    max_depth:
        Optional BFS depth cutoff

    V_real:
        List of vertices in the actual isogeny graph

    Returns
    -------

    Vertices:
        normalized projective theta points

    counterfits_really:
        Solutions to problem 2

    counterfits_almost:
        Pseudo-paths between non-isogenous abelian varieties
    """

    start = normalize_tuple(start_theta)

    vertices = {start}
    edges = defaultdict(set)

    q = deque([(start, 0)])
    visited = {start}

    parent = {start: None}

    ctr_loops = 0

    counterfits_really = []
    counterfits_almost = []
    while q:
        ctr_loops += 1
        if ctr_loops % 1000 == 0:
            print(f"size of queue: {len(q)}")
            print(f"size of V = {len(vertices)}")
        theta, depth = q.popleft()

        if max_depth is not None and depth >= max_depth:
            continue

        nbrs = radical_step_normalized(theta, only_isogs = only_isogs)

        theta_is_variety = check_riemann(theta)

        # Dead end allowed naturally if nbrs == empty set
        for tt in nbrs:
            if (not theta_is_variety) and check_riemann(tt):
                print("COUNTERFIT PATH MAYBE FOUND!!")
                path = [tt]
                cur = theta
                while cur is not None:
                    path.append(cur)
                    cur = parent[cur]
                if tt in V_real:
                    print("WOW ACTUAL COUNTERFIT PATH")
                    counterfits_really.append(path[::-1])
                else:
                    print("nvm, not isogenous...")
                    counterfits_almost.append(path[::-1])
            # Add edge theta -> tt
            edges[theta].add(tt)

            if tt not in vertices:
                vertices.add(tt)

            if tt not in visited:
                parent[tt] = theta

                visited.add(tt)
                q.append((tt, depth + 1))

    return vertices, counterfits_really, counterfits_almost

